import { promises as fs } from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = process.cwd();
await fs.rm(path.join(root, 'dist'), { recursive: true, force: true });
await build({
  entryPoints: ['index.js'],
  outfile: 'dist/index.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: ['node20'],
  sourcemap: false,
  logLevel: 'info',
  banner: {
    js: 'import { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);\n// Generated by scripts/build-host.mjs. Do not edit directly.',
  },
});
await fs.cp(path.join(root, 'builtin-actions'), path.join(root, 'dist', 'builtin-actions'), { recursive: true });
